DO $$
DECLARE u uuid; outsider uuid; w uuid; p uuid; p2 uuid; a uuid; b uuid; c uuid; m uuid; r jsonb; stamp timestamptz;
BEGIN
 SELECT id INTO u FROM public.profiles ORDER BY created_at LIMIT 1;
 SELECT id INTO outsider FROM public.profiles WHERE id<>u ORDER BY created_at LIMIT 1;
 IF u IS NULL OR outsider IS NULL THEN RAISE EXCEPTION 'Two profiles required'; END IF;
 BEGIN
 PERFORM set_config('request.jwt.claim.sub',u::text,true);
 w:=public.create_workspace('Product Development','team');
 SET LOCAL ROLE authenticated;
 INSERT INTO public.projects(workspace_id,name,owner_id,status) VALUES(w,'Website Development',u,'Active') RETURNING id INTO p;
 INSERT INTO public.projects(workspace_id,name,owner_id,status) VALUES(w,'Mobile App Development',u,'Planning') RETURNING id INTO p2;
 INSERT INTO public.tasks(workspace_id,project_id,title,status,priority,assignee_id,estimated_effort,start_date,due_date) VALUES(w,p,'Website build','doing','High',u,4,current_date-2,current_date-1) RETURNING id INTO a;
 INSERT INTO public.tasks(workspace_id,project_id,title,status,priority,assignee_id,start_date,due_date) VALUES(w,p,'Website review','todo','Medium',u,current_date,current_date+2) RETURNING id INTO b;
 INSERT INTO public.tasks(workspace_id,project_id,title,status,priority) VALUES(w,p2,'Mobile complete','done','Low') RETURNING id INTO c;
 m:=public.save_milestone(jsonb_build_object('project_id',p,'title','Website release','status','Upcoming','due_date',current_date+3),ARRAY[a,b]);
 INSERT INTO public.task_dependencies(project_id,predecessor_task_id,successor_task_id) VALUES(p,a,b);
 r:=public.workspace_analytics(w,current_date-6,current_date,current_date);
 IF (r->'kpis'->>'projects')::int<>2 THEN RAISE EXCEPTION 'Expected two projects'; END IF;
 IF (r->'kpis'->>'tasks')::int<>3 OR (r->'kpis'->>'done')::int<>1 THEN RAISE EXCEPTION 'Incorrect task counts'; END IF;
 IF (r->'kpis'->>'overdue')::int<>1 OR (r->'kpis'->>'blocked')::int<>1 THEN RAISE EXCEPTION 'Overdue or blocked counts incorrect'; END IF;
 IF (r->'team'->0->>'workload')::numeric<>7 THEN RAISE EXCEPTION 'Expected 4*1.5+1=7 workload'; END IF;
 IF (r->'milestone_stats'->>'total')::int<>1 THEN RAISE EXCEPTION 'Missing milestone'; END IF;
 IF NOT EXISTS(SELECT 1 FROM jsonb_array_elements(r->'projects') x WHERE x->>'id'=p::text AND x->>'health'='Delayed' AND x->>'progress'='0') THEN RAISE EXCEPTION 'Project health incorrect'; END IF;
 IF (r->'kpis'->>'completed_in_period')::int<>1 THEN RAISE EXCEPTION 'Completion trend missing'; END IF;
 r:=public.workspace_analytics(w,current_date-6,current_date,current_date,p);
 IF (r->'kpis'->>'tasks')::int<>2 OR (r->'kpis'->>'projects')::int<>1 THEN RAISE EXCEPTION 'Project filter ignored'; END IF;
 r:=public.workspace_analytics(w,current_date-60,current_date-30,current_date);
 IF (r->'kpis'->>'tasks')::int<>0 THEN RAISE EXCEPTION 'Date filter ignored'; END IF;
 r:=public.workspace_analytics(w,current_date-6,current_date,current_date,NULL,u,'doing','High');
 IF (r->'kpis'->>'tasks')::int<>1 THEN RAISE EXCEPTION 'Task filters ignored'; END IF;
 r:=public.workspace_analytics(w,current_date-6,current_date,current_date,NULL,NULL,NULL,NULL,0,1);
 IF jsonb_array_length(r->'tasks')<>1 OR (r->>'task_total')::int<>3 THEN RAISE EXCEPTION 'Pagination incorrect'; END IF;
 UPDATE public.tasks SET status='done',version=0 WHERE id=a;
 SELECT completed_at INTO stamp FROM public.tasks WHERE id=a;
 IF stamp IS NULL THEN RAISE EXCEPTION 'Completion timestamp missing'; END IF;
 r:=public.workspace_analytics(w,current_date-6,current_date,current_date,p);
 IF (r->'kpis'->>'blocked')::int<>0 OR (r->'projects'->0->>'progress')::int<>50 THEN RAISE EXCEPTION 'Updated analytics stale'; END IF;
 UPDATE public.tasks SET completed_at=NULL,version=1 WHERE id=a;
 IF (SELECT completed_at FROM public.tasks WHERE id=a) IS DISTINCT FROM stamp THEN RAISE EXCEPTION 'Completion timestamp can be forged'; END IF;
 UPDATE public.tasks SET status='todo',version=2 WHERE id=a;
 IF (SELECT completed_at FROM public.tasks WHERE id=a) IS NOT NULL THEN RAISE EXCEPTION 'Reopening did not clear completion'; END IF;
 PERFORM set_config('request.jwt.claim.sub',outsider::text,true);
 BEGIN PERFORM public.workspace_analytics(w,current_date-6,current_date,current_date); RAISE EXCEPTION 'Unauthorized report accepted'; EXCEPTION WHEN insufficient_privilege THEN NULL; END;
 RESET ROLE;
 UPDATE public.workspace_members SET role='viewer' WHERE workspace_id=w AND user_id=u;
 PERFORM set_config('request.jwt.claim.sub',u::text,true);
 SET LOCAL ROLE authenticated;
 r:=public.workspace_analytics(w,current_date-6,current_date,current_date);
 IF (r->'kpis'->>'tasks')::int<>3 THEN RAISE EXCEPTION 'Viewer report unavailable'; END IF;
 RESET ROLE;
 RAISE SQLSTATE 'P0002' USING MESSAGE='analytics_verified';
 EXCEPTION WHEN no_data_found THEN IF SQLERRM<>'analytics_verified' THEN RAISE; END IF; RAISE NOTICE 'Analytics assertions passed; fixtures rolled back';
 END;
END $$;
