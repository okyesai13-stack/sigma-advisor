DO $$
DECLARE u uuid; outsider uuid; w uuid; p uuid; p2 uuid; a uuid; b uuid; c uuid; m uuid; count_ integer;
BEGIN
 SELECT id INTO u FROM public.profiles ORDER BY created_at LIMIT 1;
 SELECT id INTO outsider FROM public.profiles WHERE id<>u ORDER BY created_at LIMIT 1;
 IF u IS NULL OR outsider IS NULL THEN RAISE EXCEPTION 'Two profiles required'; END IF;
 BEGIN
 PERFORM set_config('request.jwt.claim.sub',u::text,true);
 w:=public.create_workspace('Phase 3 verification','team');
 SET LOCAL ROLE authenticated;
 INSERT INTO public.projects(workspace_id,name,owner_id) VALUES(w,'Planning verification',u) RETURNING id INTO p;
 INSERT INTO public.projects(workspace_id,name,owner_id) VALUES(w,'Other project',u) RETURNING id INTO p2;
 INSERT INTO public.tasks(workspace_id,project_id,title) VALUES(w,p,'Task A') RETURNING id INTO a;
 INSERT INTO public.tasks(workspace_id,project_id,title) VALUES(w,p,'Task B') RETURNING id INTO b;
 INSERT INTO public.tasks(workspace_id,project_id,title) VALUES(w,p2,'Other task') RETURNING id INTO c;
 m:=public.save_milestone(jsonb_build_object('project_id',p,'title','Release','status','Upcoming'),ARRAY[a,b]);
 SELECT count(*) INTO count_ FROM public.milestone_tasks WHERE milestone_id=m;
 IF count_<>2 THEN RAISE EXCEPTION 'Task links missing'; END IF;
 BEGIN UPDATE public.milestones SET status='Completed',version=1 WHERE id=m; RAISE EXCEPTION 'Incomplete completion accepted'; EXCEPTION WHEN raise_exception THEN IF SQLERRM='Incomplete completion accepted' THEN RAISE; END IF; END;
 INSERT INTO public.task_dependencies(project_id,predecessor_task_id,successor_task_id) VALUES(p,a,b);
 BEGIN INSERT INTO public.task_dependencies(project_id,predecessor_task_id,successor_task_id) VALUES(p,b,a); RAISE EXCEPTION 'Cycle accepted'; EXCEPTION WHEN raise_exception THEN IF SQLERRM='Cycle accepted' THEN RAISE; END IF; END;
 BEGIN INSERT INTO public.task_dependencies(project_id,predecessor_task_id,successor_task_id) VALUES(p,a,c); RAISE EXCEPTION 'Cross project accepted'; EXCEPTION WHEN foreign_key_violation THEN NULL; END;
 BEGIN INSERT INTO public.milestone_tasks(project_id,milestone_id,task_id) VALUES(p,m,c); RAISE EXCEPTION 'Cross project milestone accepted'; EXCEPTION WHEN foreign_key_violation THEN NULL; END;
 UPDATE public.tasks SET start_date='2026-11-16',due_date='2026-11-20',version=0 WHERE id=a;
 SELECT count(*) INTO count_ FROM public.project_schedule_activity WHERE project_id=p AND event='tasks update';
 IF count_<>1 THEN RAISE EXCEPTION 'Date activity not recorded'; END IF;
 UPDATE public.milestones SET status='Completed',completion_override_reason='Approved release exception',version=1 WHERE id=m;
 SELECT count(*) INTO count_ FROM public.project_schedule_activity WHERE project_id=p AND event='Milestone completion override';
 IF count_<>1 THEN RAISE EXCEPTION 'Override history missing'; END IF;
 UPDATE public.tasks SET status='done',version=1 WHERE id=a;
 UPDATE public.tasks SET status='done',version=0 WHERE id=b;
 SELECT count(*) INTO count_ FROM public.tasks t JOIN public.milestone_tasks l ON l.task_id=t.id WHERE l.milestone_id=m AND t.status='done';
 IF count_<>2 THEN RAISE EXCEPTION 'Linked task completion incorrect'; END IF;
 PERFORM set_config('request.jwt.claim.sub',outsider::text,true);
 SELECT count(*) INTO count_ FROM public.milestones WHERE id=m;
 IF count_<>0 THEN RAISE EXCEPTION 'Unauthorized milestone leaked'; END IF;
 SELECT count(*) INTO count_ FROM public.task_dependencies WHERE project_id=p;
 IF count_<>0 THEN RAISE EXCEPTION 'Unauthorized dependency leaked'; END IF;
 RESET ROLE;
 UPDATE public.workspace_members SET role='viewer' WHERE workspace_id=w AND user_id=u;
 PERFORM set_config('request.jwt.claim.sub',u::text,true);
 SET LOCAL ROLE authenticated;
 BEGIN INSERT INTO public.task_dependencies(project_id,predecessor_task_id,successor_task_id) VALUES(p,b,a); RAISE EXCEPTION 'Viewer dependency accepted'; EXCEPTION WHEN insufficient_privilege THEN NULL; WHEN raise_exception THEN IF SQLERRM='Viewer dependency accepted' THEN RAISE; END IF; END;
 BEGIN PERFORM public.save_milestone(jsonb_build_object('project_id',p,'title','Viewer write'),ARRAY[a]); RAISE EXCEPTION 'Viewer milestone accepted'; EXCEPTION WHEN raise_exception THEN IF SQLERRM='Viewer milestone accepted' THEN RAISE; END IF; END;
 RESET ROLE;
 RAISE SQLSTATE 'P0002' USING MESSAGE='verification_passed';
 EXCEPTION WHEN no_data_found THEN IF SQLERRM<>'verification_passed' THEN RAISE; END IF; RAISE NOTICE 'Phase 3 planning checks passed; all fixtures rolled back';
 END;
END $$;
